WITH e AS (SELECT * FROM governance_events WHERE occurred_at >= $1 AND occurred_at <= $2),
v AS (SELECT
 count(*) FILTER (WHERE event_type='consult' AND COALESCE((payload->'counters'->>'match_count')::numeric,0)>0)::float8 consult_n,
 count(*) FILTER (WHERE event_type='consult')::float8 consult_d,
 count(*) FILTER (WHERE event_type='check' AND payload->'labels'->>'outcome'='pass')::float8 warning_n,
 count(*) FILTER (WHERE event_type='check' AND payload->'labels'->>'outcome' IN ('pass','warn','block'))::float8 warning_d,
 count(*) FILTER (WHERE event_type='check' AND payload->'labels'->>'outcome'='pass')::float8 coverage_n,
 count(*) FILTER (WHERE event_type='check')::float8 coverage_d,
 count(*) FILTER (WHERE event_type='ci_gate' AND payload->'labels'->>'outcome'='block')::float8 escape_n,
 count(*) FILTER (WHERE event_type='ci_gate')::float8 escape_d,
 sum(COALESCE((payload->'counters'->>'changed_line_count')::numeric,0))::float8 rework_n,
 sum(COALESCE((payload->'counters'->>'consult_count')::numeric,0))::float8 rework_d,
 count(*) FILTER (WHERE event_type='check' AND payload->'labels'->>'outcome'='warn')::float8 mismatch_n,
 count(*) FILTER (WHERE event_type='check')::float8 mismatch_d,
 count(*)::bigint samples FROM e),
SELECT jsonb_build_object('consult_n',consult_n,'consult_d',consult_d,'warning_n',warning_n,'warning_d',warning_d,
 'coverage_n',coverage_n,'coverage_d',coverage_d,'escape_n',escape_n,'escape_d',escape_d,'rework_n',rework_n,
 'rework_d',rework_d,'mismatch_n',mismatch_n,'mismatch_d',mismatch_d,'samples',samples,
 'age_0_30',(SELECT count(*) FROM rule_lifecycles WHERE activated_at>=now()-interval '30 days'),
 'age_31_90',(SELECT count(*) FROM rule_lifecycles WHERE activated_at<now()-interval '30 days' AND activated_at>=now()-interval '90 days'),
 'age_91_180',(SELECT count(*) FROM rule_lifecycles WHERE activated_at<now()-interval '90 days' AND activated_at>=now()-interval '180 days'),
 'age_over_180',(SELECT count(*) FROM rule_lifecycles WHERE activated_at<now()-interval '180 days'),
 'age_unknown',(SELECT count(*) FROM rule_lifecycles WHERE activated_at IS NULL),
 'last_received_at',(SELECT max(received_at) FROM e)) FROM v;
